describe("Anx bounded native cover cache", function()
    local Covers, Scope, SQ3, ffi, zstd, BB, scope, covers, database, file, attr
    setup(function()
        require("commonrequire")
        Covers = dofile("plugins/anxui.koplugin/covers.lua")
        Scope = dofile("plugins/anxui.koplugin/lifecycle.lua")
        SQ3, ffi, zstd = require("lua-ljsqlite3/init"), require("ffi"), require("ffi/zstd")
        BB = require("ffi/blitbuffer")
        file = "spec/front/unit/data/juliet.epub"
        attr = require("libs/libkoreader-lfs").attributes(file)
    end)
    before_each(function()
        database = os.tmpname()
        scope = Scope.new()
        covers = Covers.new(scope, {}, true)
        covers.database = database
        covers.manager = function() return {} end
    end)
    after_each(function()
        scope:close()
        os.remove(database)
        require("ui/uimanager"):quit()
    end)
    local function cache(width, height, stride, data, size)
        local db = SQ3.open(database)
        db:exec([[CREATE TABLE bookinfo (directory TEXT, filename TEXT, title TEXT, authors TEXT,
            cover_fetched TEXT, has_cover TEXT, ignore_cover TEXT, cover_w INTEGER, cover_h INTEGER,
            cover_bb_type INTEGER, cover_bb_stride INTEGER, cover_bb_data BLOB, filesize INTEGER,
            filemtime INTEGER, ignore_meta TEXT, cover_sizetag TEXT, in_progress INTEGER)]])
        local stmt = db:prepare("INSERT INTO bookinfo VALUES (?, ?, 'Title', 'Author', 'Y', 'Y', NULL, ?, ?, ?, ?, ?, ?, ?, NULL, '8x8', 0)")
        local directory, filename = require("util").splitFilePathName(file)
        -- This binding consumes/free()s the passed pointer after SQLite copies
        -- it; do not pass a Lua-owned ffi array or the caller's original buffer.
        local stored = ffi.C.malloc(size)
        ffi.copy(stored, data, size)
        stmt:bind(directory, filename, width, height, BB.TYPE_BB8, stride, SQ3.blob(stored, size), attr.size, attr.modification):step()
        stmt:close(); db:close()
    end
    it("loads a genuine compressed bitmap and releases its memory with the page", function()
        local pixels = ffi.new("uint8_t[64]", 128)
        local compressed, size = zstd.zstd_compress(pixels, 64)
        cache(8, 8, 8, compressed, size)
        ffi.C.free(compressed)
        local info = covers:read(file)
        assert.are.equal("Title", info.title)
        assert.are.equal(8, info.cover:getWidth())
        assert.are.equal(320, covers.bytes)
        scope:close()
        assert.are.equal(0, covers.bytes)
        assert.are.equal(0, #covers.buffers)
    end)
    it("rejects oversized dimensions before decoding", function()
        local data = ffi.new("char[4]", "bad")
        cache(100000, 100000, 100000, data, 4)
        local info = covers:read(file)
        assert.are.equal("invalid_cover", info.error)
        assert.is_nil(info.cover)
        assert.are.equal(0, covers.bytes)
    end)
    it("rejects corrupt compressed data without allocating a bitmap", function()
        local data = ffi.new("char[4]", "bad")
        cache(8, 8, 8, data, 4)
        assert.are.equal("invalid_cover", covers:read(file).error)
        assert.are.equal(0, covers.bytes)
    end)
    it("enforces the budget before decoding even a valid cover", function()
        local pixels = ffi.new("uint8_t[64]")
        local compressed, size = zstd.zstd_compress(pixels, 64)
        cache(8, 8, 8, compressed, size)
        ffi.C.free(compressed)
        covers.limit = 100
        assert.are.equal("cover_limit", covers:read(file).error)
        assert.are.equal(0, covers.bytes)
    end)
end)
